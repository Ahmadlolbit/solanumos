func (context *Context) hyprlockSetup(*runlog.Log) error {
	clock := "$TIME"
	if context.Config.Get("CLOCK_FORMAT") == "12h" {
		clock = "$TIME12"
	}
	finger, placeholder, wrong := "false", "Password", "Wrong password"
	if context.Config.Get("FINGERPRINT") == "yes" {
		finger, placeholder, wrong = "true", "Password or finger", "Wrong password or finger"
	}
	return context.Deploy.File("system/hypr/hyprlock.conf", hyprSystem+"hyprlock.conf", "TIME="+clock, "FINGERPRINT="+finger, "PLACEHOLDER="+placeholder, "FAIL="+wrong+" · try $ATTEMPTS")
}

func idleListener(timeout int, action, resume string) string {
	text := fmt.Sprintf("\nlistener {\n    timeout = %d\n    on-timeout = %s\n", timeout, action)
	if resume != "" {
		text += "    on-resume = " + resume + "\n"
	}
	return text + "}\n"
}

func dimListeners(at int) string {
	return idleListener(at, "brightnessctl -s set 10%", "brightnessctl -r") +
		idleListener(at, "brightnessctl -sd '*::kbd_backlight' set 0", "brightnessctl -rd '*::kbd_backlight'")
}

func lockListeners(lock int) string {
	var text strings.Builder
	if lock > secondsAMin {
		text.WriteString(dimListeners(lock - dimAhead))
	}
	text.WriteString(idleListener(lock, "loginctl lock-session", ""))
	text.WriteString(idleListener(lock+dimAhead, dpmsOff, dpmsOn))
	return text.String()
}

func screenOffListeners(saver int) string {
	off := saver + screenOff
	return dimListeners(off-dimAhead) + idleListener(off, saverStop+dpmsOff, dpmsOn)
}

func hypridleConfig(lock, suspend, saver int) string {
	var text strings.Builder
	text.WriteString("general {\n    lock_cmd = pgrep -xu \"$(id -u)\" hyprlock >/dev/null || hyprlock\n    before_sleep_cmd = loginctl lock-session\n")
	text.WriteString("    after_sleep_cmd = " + dpmsOn + "\n}\n")
	if saver > 0 && (lock == 0 || saver < lock) {
		text.WriteString(idleListener(saver, "solanum-screensaver start --idle", ""))
	}
	if lock > 0 {
		text.WriteString(lockListeners(lock))
	} else {
		text.WriteString(screenOffListeners(saver))
	}
	if suspend > 0 {
		text.WriteString(idleListener(suspend, "systemctl suspend", ""))
	}
	return text.String()
}

func (context *Context) seconds(key string) int {
	minutes, _ := strconv.Atoi(context.Config.Get(key))
	return minutes * secondsAMin
}

func (context *Context) hypridleSetup(*runlog.Log) error {
	text := hypridleConfig(context.seconds("IDLE_LOCK_MINUTES"), context.seconds("IDLE_SUSPEND_MINUTES"), context.seconds("SCREENSAVER_MINUTES"))
	_, err := context.Deploy.Content([]byte(text), hyprSystem+"hypridle.conf")
	return err
}

func (context *Context) makoSetup(log *runlog.Log) error {
	changed, err := context.Deploy.Changed("config/mako/defaults", filepath.Join(env.ShareDir(), "mako/defaults"))
	if err != nil {
		return err
	}
	if err := context.Deploy.UserOnce("config/mako/config", makoUser); err != nil {
		return err
	}
	if changed && context.Person.SessionRunning() {
		context.Person.Run(log, "makoctl", "reload")
	}
	return nil
}

func (context *Context) walkerInstall(log *runlog.Log) error {
	if err := fetch.ReleaseExtract(log, "walker", "walker", filepath.Join(env.BinDir(), "walker"), programMode); err != nil {
		return err
	}
	if err := fetch.ReleaseExtract(log, "elephant", "elephant-linux-amd64", filepath.Join(env.BinDir(), "elephant"), programMode); err != nil {
		return err
	}
	for _, provider := range elephantProviders {
		if err := fetch.ReleaseExtract(log, "elephant-"+provider, provider+"-linux-amd64.so", filepath.Join(elephantLib, provider+".so"), plainMode); err != nil {
			return err
		}
	}
	for _, old := range []string{"/etc/xdg/walker/themes/hyprtrixie", "/etc/xdg/elephant/menus"} {
		if err := context.Deploy.RemoveTree(old); err != nil {
			return err
		}
	}
	if err := context.Deploy.Remove(filepath.Join(env.BinDir(), "hyprtrixie-power-menu"), filepath.Join(elephantLib, "menus.so")); err != nil {
		return err
	}
	return context.Deploy.File("system/walker/config.toml", "/etc/xdg/walker/config.toml")
}

func walkerReady(*runlog.Log) error {
	if err := apt.Commands("walker", "elephant"); err != nil {
		return err
	}
	for _, provider := range elephantProviders {
		if err := fileThere(filepath.Join(elephantLib, provider+".so")); err != nil {
			return err
		}
	}
	return nil
}

func (context *Context) commandInstall(*runlog.Log) error {
	for _, folder := range []string{env.BinDir(), env.StateDir()} {
		if err := os.MkdirAll(folder, programMode); err != nil {
			return err
		}
	}
	if err := context.Deploy.Link(filepath.Join(env.Root(), "solanum"), pkexec.Record()); err != nil {
		return err
	}
	if err := context.Deploy.Tool("solanum-core"); err != nil {
		return err
	}
	return context.Deploy.Link(filepath.Join(env.BinDir(), "solanum-core"), filepath.Join(env.BinDir(), "solanum"))
}

func pointsAt(link, want string) error {
	got, err := fsutil.RealPath(link)
	if err != nil {
		return err
	}
	wanted, err := fsutil.RealPath(want)
	if err != nil {
		return err
	}
	return expect(got == wanted, "it points at "+got)
}

func commandReady(*runlog.Log) error {
	if err := pointsAt(pkexec.Record(), filepath.Join(env.Root(), "solanum")); err != nil {
		return err
	}
	return pointsAt(filepath.Join(env.BinDir(), "solanum"), filepath.Join(env.BinDir(), "solanum-core"))
}

func (context *Context) tipsInstall(*runlog.Log) error {
	if err := context.Deploy.File("system/tips.txt", filepath.Join(env.ShareDir(), "tips.txt")); err != nil {
		return err
	}
	if err := context.Deploy.Tool("solanum-tip"); err != nil {
		return err
	}
	settings := context.Config
	return context.Deploy.File("system/tips.conf", "/etc/solanum/tips", "TERMINAL="+settings.Get("TIPS_TERMINAL"),
		"WELCOME="+settings.Get("TIPS_WELCOME"), "NOTIFY="+settings.Get("TIPS_NOTIFY"))
}

func (context *Context) deployUserUnits(units ...string) (bool, error) {
	changed := false
	for _, unit := range units {
		moved, err := context.Deploy.Changed("system/systemd/"+unit, userUnits+unit)
		changed = changed || moved
		if err != nil {
			return changed, err
		}
	}
	return changed, nil
}

func everyoneTimer(log *runlog.Log, timer string, on, changed bool) error {
	if !changed && fsutil.IsLink(userUnits+"timers.target.wants/"+timer) == on {
		return nil
	}
	action := "disable"
	if on {
		action = "enable"
	}
	return run.Logged(log, "systemctl", "--global", action, timer)
}

func liveImage() bool {
	return os.Getenv("SOLANUM_LIVE") == "1"
}

func (context *Context) tipTimerInstall(log *runlog.Log) error {
	changed, err := context.deployUserUnits(tipService, tipTimer)
	if err != nil {
		return err
	}
	return everyoneTimer(log, tipTimer, !liveImage(), changed)
}

func (context *Context) careInstall(log *runlog.Log) error {
	if err := context.Deploy.Tool("solanum-care"); err != nil {
		return err
	}
	changed, err := context.deployUserUnits(careService, careTimer)
	if err != nil {
		return err
	}
	return everyoneTimer(log, careTimer, !liveImage() && context.Config.Get("CARE_NOTIFY") == "yes", changed)
}

func (context *Context) brightnessAccess(log *runlog.Log) error {
	rules := followUp{name: "brightness-rules"}
	changed, err := context.Deploy.Changed("system/udev/90-solanum-brightness.rules", "/etc/udev/rules.d/90-solanum-brightness.rules")
	rules.need(changed)
	if err != nil {
		return err
	}
	if err := context.Person.AddGroups(log, "video"); err != nil {
		return err
	}
	return rules.do(func() error {
		run.Logged(log, "udevadm", "control", "--reload")
		return run.Logged(log, "udevadm", "trigger", "--subsystem-match=backlight", "--subsystem-match=leds", "--action=add")
	})
}

func (context *Context) toolStep(title, tool string) {
	context.Run.Step(title, func(*runlog.Log) error { return context.Deploy.Tool(tool) })
}

func timerCheck(timer string) step.Work {
	return func(*runlog.Log) error {
		return expect(fsutil.IsLink(userUnits+"timers.target.wants/"+timer), timer+" isn't enabled")
	}
}

