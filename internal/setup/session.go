const (
	hyprSystem  = "/etc/xdg/hypr/"
	hyprUser    = ".config/hypr/hyprland.lua"
	appsMenu    = "/etc/xdg/menus/solanum-applications.menu"
	makoUser    = ".config/mako/config"
	elephantLib = "/usr/local/lib/elephant"
	tipTimer    = "solanum-tip.timer"
	tipService  = "solanum-tip.service"
	careTimer   = "solanum-care.timer"
	careService = "solanum-care.service"
	fwupdTimer  = "fwupd-refresh.timer"
	userUnits   = "/etc/systemd/user/"
	screensCall = "timeout 2 qs -p /usr/share/solanum/shell ipc call screens "
	dpmsOn      = `hyprctl dispatch 'hl.dsp.dpms({action = "on"})'; ` + screensCall + "on"
	dpmsOff     = screensCall + `off; hyprctl dispatch 'hl.dsp.dpms({action = "off"})'`
	secondsAMin = 60
	dimAhead    = 30
	screenOff   = 10 * secondsAMin
	saverStop   = "solanum-screensaver stop; "
)

var elephantProviders = []string{"desktopapplications", "calc", "runner", "files", "symbols", "websearch", "clipboard", "providerlist", "unicode"}

func hyprShare() string {
	return filepath.Join(env.ShareDir(), "hypr")
}

func luaBool(value string) string {
	if value == "yes" {
		return "true"
	}
	return "false"
}

func luaScale(value string) string {
	if value == "auto" {
		return `"auto"`
	}
	return value
}

func (context *Context) hyprlandDefaults(log *runlog.Log) error {
	if err := context.Deploy.Tree("config/hypr", hyprShare()); err != nil {
		return err
	}
	if err := context.Deploy.File("system/hypr/hyprland.lua", hyprSystem+"hyprland.lua"); err != nil {
		return err
	}
	changed, err := context.Deploy.Changed("system/xdg-applications.menu", appsMenu)
	if err != nil || !changed {
		return err
	}
	stale, err := filepath.Glob(context.Person.Path(".cache/ksycoca6_*"))
	if err != nil {
		return err
	}
	return context.removeYours(log, stale...)
}

func nvidiaDrivesDisplay(hardware detect.Hardware, graphics string) bool {
	return graphics == "proprietary" && hardware.HasGPU("nvidia") && !hardware.NvidiaLegacy && !hardware.Hybrid()
}

func (context *Context) hyprlandOptions(*runlog.Log) error {
	settings := context.Config
	return context.Deploy.File("system/hypr/options.lua", "/etc/solanum/hypr/options.lua",
		"NATURAL_SCROLL="+luaBool(settings.Get("NATURAL_SCROLL")), "TAP_TO_CLICK="+luaBool(settings.Get("TAP_TO_CLICK")),
		"ANIMATIONS="+luaBool(settings.Get("ANIMATIONS")), "SCALE="+luaScale(settings.Get("DISPLAY_SCALE")),
		"NVIDIA="+strconv.FormatBool(nvidiaDrivesDisplay(context.hardware(), settings.Get("GRAPHICS"))))
}

func (context *Context) hyprlandUserConfig(log *runlog.Log) error {
	file := context.Person.Path(hyprUser)
	if fsutil.IsFile(file) && mentions(file, "autogenerated = true") {
		if err := context.Person.Run(log, "mv", "-fT", file, file+".solanum-old"); err != nil {
			return err
		}
	}
	return context.Deploy.UserOnce("system/hypr/hyprland.lua", hyprUser)
}

